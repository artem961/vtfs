CREATE TABLE inodes (
    ino bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    mode integer NOT NULL CHECK (mode BETWEEN 0 AND 65535 AND (mode & 61440) IN (16384, 32768)),
    uid bigint NOT NULL CHECK (uid BETWEEN 0 AND 4294967294),
    gid bigint NOT NULL CHECK (gid BETWEEN 0 AND 4294967294),
    nlink bigint NOT NULL CHECK (nlink BETWEEN 0 AND 4294967295),
    atime bigint NOT NULL,
    mtime bigint NOT NULL,
    ctime bigint NOT NULL
);

CREATE TABLE dentries (
    parent_ino bigint NOT NULL REFERENCES inodes (ino),
    name text NOT NULL CHECK (
        octet_length(name) BETWEEN 1 AND 255
        AND position('/' IN name) = 0
        AND name NOT IN ('.', '..')
    ),
    ino bigint NOT NULL REFERENCES inodes (ino),
    position bigint GENERATED ALWAYS AS IDENTITY (START WITH 2) UNIQUE,
    PRIMARY KEY (parent_ino, name)
);

CREATE INDEX dentries_listing ON dentries (parent_ino, position);

